#!/bin/bash
# persona-reflux.sh — weekly pass: grep 🔒 corrections out of
# session_notes/ and journals/, append them as review proposals. Does NOT
# judge or apply anything -- it surfaces raw material. The agent fills in
# the "Proposed self_persona change" field when it reviews the file with
# the human; the human approves/rejects; the agent (not this script) edits
# self_persona.md.
#
# Safe to run repeatedly (daily, weekly, or by hand) -- .reflux-seen
# dedupes so a given 🔒 line is only ever proposed once.

set -o pipefail
shopt -s nullglob

MEM="${MEM:-$PWD}"
REVIEW_DIR="$MEM/.review"
PROPOSALS_FILE="$REVIEW_DIR/reflux-proposals.md"
SEEN_FILE="$REVIEW_DIR/.reflux-seen"

mkdir -p "$REVIEW_DIR" "$MEM/session_notes" "$MEM/journals"
touch "$SEEN_FILE"

if [ ! -f "$PROPOSALS_FILE" ]; then
  cat > "$PROPOSALS_FILE" <<EOF
# Persona Reflux Proposals

Generated by scripts/persona-reflux.sh. Each block below is one 🔒
correction found in session_notes/ or journals/. Review with the human,
set Status to APPROVED or REJECTED, then apply APPROVED entries to
self_persona.md and mark them APPLIED.
EOF
fi

NOTE_FILES=("$MEM"/session_notes/*.md)
JOURNAL_FILES=("$MEM"/journals/*.md)

if [ ${#NOTE_FILES[@]} -eq 0 ] && [ ${#JOURNAL_FILES[@]} -eq 0 ]; then
  echo "no session notes or journals yet" >&2
  exit 0
fi

NEW=0

while IFS= read -r match; do
  [ -z "$match" ] && continue
  file="${match%%:*}"
  rest="${match#*:}"
  line="${rest%%:*}"
  content="${rest#*:}"

  key="${file}:${line}"
  grep -qxF "$key" "$SEEN_FILE" && continue

  date_guess="$(basename "$file" .md)"
  case "$date_guess" in
    [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]) : ;;
    *) date_guess="unknown" ;;
  esac

  correction="$(printf '%s' "$content" | sed -E 's/^[[:space:]]*[-*]?[[:space:]]*🔒[[:space:]]*//')"

  {
    echo ""
    echo "---"
    echo "**Date**: ${date_guess}"
    echo "**Source**: ${file}:${line}"
    echo "**Correction**: ${correction}"
    echo "**Proposed self_persona change**: (agent fills in on review)"
    echo "**Status**: PENDING"
  } >> "$PROPOSALS_FILE"

  echo "$key" >> "$SEEN_FILE"
  NEW=$((NEW + 1))
# Anchor to line-lead 🔒 (optional whitespace/bullet first) -- the same shape
# the sed strip above assumes. A bare mid-line mention ("🔒 lines below"
# quoted in prose) is not a correction; the agent's own boot test caught the
# unanchored grep proposing one (Scheherazade 07-13, verified raw here).
done < <(grep -nE '^[[:space:]]*[-*]?[[:space:]]*🔒' "${NOTE_FILES[@]}" "${JOURNAL_FILES[@]}" 2>/dev/null)

echo "${NEW} new correction(s) added to ${PROPOSALS_FILE}" >&2
