#!/usr/bin/env node
// persona-reflux.mjs -- weekly pass: grep 🔒 corrections out of
// session_notes/ and journals/, append them as review proposals. Node port
// of persona-reflux.sh (win-port Phase 3). Does NOT judge or apply
// anything -- it surfaces raw material. The agent fills in the "Proposed
// self_persona change" field when it reviews the file with the human; the
// human approves/rejects; the agent (not this script) edits
// self_persona.md.
//
// Safe to run repeatedly (daily, weekly, or by hand) -- .reflux-seen
// dedupes so a given 🔒 line is only ever proposed once.
//
// Two lessons carried over VERBATIM from the bash version (both caught by
// Scheherazade's own boot tests, 07-13, verified raw at the time):
//   1. Anchor to line-lead 🔒 (optional whitespace/bullet first). A bare
//      mid-line mention ("🔒 lines below" quoted in prose) is not a
//      correction; the unanchored grep proposed one.
//   2. Keys are ALWAYS file:line. bash grep without -H drops the filename
//      when only ONE file matches, shifting the parse and corrupting
//      .reflux-seen keys. The port builds keys from its own iteration, so
//      the single-file case is structurally immune -- the test still pins it.

import fs from 'node:fs'
import path from 'node:path'

const MEM = process.env.MEM || process.cwd()
const REVIEW_DIR = path.join(MEM, '.review')
const PROPOSALS_FILE = path.join(REVIEW_DIR, 'reflux-proposals.md')
const SEEN_FILE = path.join(REVIEW_DIR, '.reflux-seen')

fs.mkdirSync(REVIEW_DIR, { recursive: true })
fs.mkdirSync(path.join(MEM, 'session_notes'), { recursive: true })
fs.mkdirSync(path.join(MEM, 'journals'), { recursive: true })
if (!fs.existsSync(SEEN_FILE)) fs.writeFileSync(SEEN_FILE, '')

if (!fs.existsSync(PROPOSALS_FILE)) {
  fs.writeFileSync(PROPOSALS_FILE, `# Persona Reflux Proposals

Generated by scripts/persona-reflux.mjs. Each block below is one 🔒
correction found in session_notes/ or journals/. Review with the human,
set Status to APPROVED or REJECTED, then apply APPROVED entries to
self_persona.md and mark them APPLIED.
`)
}

function mdFiles(dir) {
  if (!fs.existsSync(dir)) return []
  return fs.readdirSync(dir)
    .filter((f) => f.endsWith('.md') && fs.statSync(path.join(dir, f)).isFile())
    .sort()
    .map((f) => path.join(dir, f))
}

const files = [...mdFiles(path.join(MEM, 'session_notes')), ...mdFiles(path.join(MEM, 'journals'))]
if (files.length === 0) {
  console.error('no session notes or journals yet')
  process.exit(0)
}

const seen = new Set(fs.readFileSync(SEEN_FILE, 'utf8').split('\n').filter(Boolean))
// Lesson 1: line-lead anchor. Same shape the strip below assumes.
const LOCK_LINE = /^[\s]*[-*]?[\s]*🔒/
let added = 0

for (const file of files) {
  const lines = fs.readFileSync(file, 'utf8').split('\n')
  for (let i = 0; i < lines.length; i++) {
    if (!LOCK_LINE.test(lines[i])) continue
    const key = `${file}:${i + 1}` // Lesson 2: file:line, built structurally
    if (seen.has(key)) continue

    const base = path.basename(file, '.md')
    const dateGuess = /^\d{4}-\d{2}-\d{2}$/.test(base) ? base : 'unknown'
    const correction = lines[i].replace(/^[\s]*[-*]?[\s]*🔒[\s]*/, '')

    fs.appendFileSync(PROPOSALS_FILE, `
---
**Date**: ${dateGuess}
**Source**: ${file}:${i + 1}
**Correction**: ${correction}
**Proposed self_persona change**: (agent fills in on review)
**Status**: PENDING
`)
    fs.appendFileSync(SEEN_FILE, `${key}\n`)
    seen.add(key)
    added++
  }
}

console.error(`${added} new correction(s) added to ${PROPOSALS_FILE}`)
