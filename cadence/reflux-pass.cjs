'use strict'
// cadence/reflux-pass.cjs -- the reflux pass itself, callable in-process.
//
// Grep line-lead 🔒 corrections out of session_notes/ and journals/ and append
// each new one as a PENDING block to .review/reflux-proposals.md, deduped by
// .review/.reflux-seen. It does NOT judge or apply anything: it surfaces raw
// material, the agent fills the "Proposed self_persona change" field when it
// reviews with the human, and only the agent (never this code) edits
// self_persona.md.
//
// Two callers, one rule:
//   * scripts/persona-reflux.mjs -- the CLI the agent runs by hand
//     (procedures/persona-reflux.md step 1). Kept byte-compatible: same
//     stderr lines, same eager .review/ creation.
//   * cadence/daily-clock.cjs -- the app's once-a-day clock (0.3.5). That
//     caller passes lazy:true, so a pass that finds nothing new creates no
//     directory and no file: a fresh install must not grow a .review/ header
//     that the "!" reader would then have to parse as zero.
//
// Two lessons carried over VERBATIM from the bash version (both caught by the
// agent's own boot tests, 07-13, verified raw at the time):
//   1. Anchor to line-lead 🔒 (optional whitespace/bullet first). A bare
//      mid-line mention ("🔒 lines below" quoted in prose) is not a
//      correction; the unanchored grep proposed one.
//   2. Keys are ALWAYS file:line, built from this loop's own iteration, so the
//      single-file case (bash grep without -H) is structurally immune.

const fs = require('node:fs')
const path = require('node:path')

const PROPOSALS_HEADER = `# Persona Reflux Proposals

Generated by scripts/persona-reflux.mjs. Each block below is one 🔒
correction found in session_notes/ or journals/. Review with the human,
set Status to APPROVED or REJECTED, then apply APPROVED entries to
self_persona.md and mark them APPLIED.
`

// Lesson 1: line-lead anchor. Same shape the strip below assumes.
const LOCK_LINE = /^[\s]*[-*]?[\s]*🔒/

function refluxPaths(mem) {
  const reviewDir = path.join(mem, '.review')
  return {
    reviewDir,
    proposalsFile: path.join(reviewDir, 'reflux-proposals.md'),
    seenFile: path.join(reviewDir, '.reflux-seen'),
  }
}

function mdFiles(dir) {
  if (!fs.existsSync(dir)) return []
  return fs.readdirSync(dir)
    .filter((f) => f.endsWith('.md') && fs.statSync(path.join(dir, f)).isFile())
    .sort()
    .map((f) => path.join(dir, f))
}

// The source files a pass reads, in the order it reads them.
function sourceFiles(mem) {
  return [...mdFiles(path.join(mem, 'session_notes')), ...mdFiles(path.join(mem, 'journals'))]
}

// Create .review/, the seen file and the proposals header if absent. The CLI
// calls this up front (its historic behavior); the lazy pass only when it has
// a proposal to append.
function ensureReviewFiles(mem) {
  const { reviewDir, proposalsFile, seenFile } = refluxPaths(mem)
  fs.mkdirSync(reviewDir, { recursive: true })
  if (!fs.existsSync(seenFile)) fs.writeFileSync(seenFile, '')
  if (!fs.existsSync(proposalsFile)) fs.writeFileSync(proposalsFile, PROPOSALS_HEADER)
}

// runRefluxPass({ mem, lazy }) -> { added, files, proposalsFile }
//   files  = how many source files were scanned (0 = nothing to reflux from)
//   added  = how many new PENDING blocks were appended
function runRefluxPass({ mem, lazy = false }) {
  const { proposalsFile, seenFile } = refluxPaths(mem)
  if (!lazy) ensureReviewFiles(mem)

  const files = sourceFiles(mem)
  if (files.length === 0) return { added: 0, files: 0, proposalsFile }

  let seen = new Set()
  try {
    seen = new Set(fs.readFileSync(seenFile, 'utf8').split('\n').filter(Boolean))
  } catch { /* no seen file yet: nothing proposed so far */ }

  let added = 0
  for (const file of files) {
    const lines = fs.readFileSync(file, 'utf8').split('\n')
    for (let i = 0; i < lines.length; i++) {
      if (!LOCK_LINE.test(lines[i])) continue
      const key = `${file}:${i + 1}` // Lesson 2: file:line, built structurally
      if (seen.has(key)) continue

      if (added === 0 && lazy) ensureReviewFiles(mem)
      const base = path.basename(file, '.md')
      const dateGuess = /^\d{4}-\d{2}-\d{2}$/.test(base) ? base : 'unknown'
      const correction = lines[i].replace(/^[\s]*[-*]?[\s]*🔒[\s]*/, '')

      fs.appendFileSync(proposalsFile, `
---
**Date**: ${dateGuess}
**Source**: ${file}:${i + 1}
**Correction**: ${correction}
**Proposed self_persona change**: (agent fills in on review)
**Status**: PENDING
`)
      fs.appendFileSync(seenFile, `${key}\n`)
      seen.add(key)
      added++
    }
  }
  return { added, files: files.length, proposalsFile }
}

module.exports = { runRefluxPass, ensureReviewFiles, sourceFiles, refluxPaths, LOCK_LINE, PROPOSALS_HEADER }
