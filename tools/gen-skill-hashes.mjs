// gen-skill-hashes.mjs — generate onboarding/templates/skill-hashes.json,
// the accumulated manifest of every skill-file version this repo has ever
// shipped (v0.1.11 "overwrite-if-pristine" seeding — pattern from stablyai/orca
// snapshot-registry, docs/research-orca-ade-20260814.md in the MAGI repo).
//
// For every file under the skill roots, across ALL commits reachable from
// HEAD plus the current working tree, record the normalized (CRLF/CR→LF)
// sha256. At boot, harness-render's seeding compares an installed skill file
// against this set: matching any historical hash proves the copy is pristine
// (just possibly stale) and safe to overwrite; matching none means the user
// edited it and it must be left alone.
//
// Run after editing any skill template, and commit the result:
//   node tools/gen-skill-hashes.mjs
// test-skill-versioning.mjs fails the suite if the manifest is stale.
//
// Normalization matches harness-render.cjs normalizedSkillHash: utf8,
// \r\n→\n then \r→\n. Line-ending churn (Windows checkouts, editor saves)
// must not read as "user modified".

import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT_PATH = path.join(REPO_ROOT, 'onboarding', 'templates', 'skill-hashes.json')

// Roots whose files get seeded into CONFIG_DIR/.claude/skills. Keys in the
// manifest are "<skill-dir>/<relative-path>" under each root, so both roots
// share one namespace — same as SKILLS_DIR itself.
const SKILL_ROOTS = [
  'onboarding/templates/skills',
  'vendor/chromux/skills',
]

const git = (...args) =>
  execFileSync('git', args, { cwd: REPO_ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })

const normalizedSha256 = (buf) =>
  crypto.createHash('sha256')
    .update(buf.toString('utf8').replace(/\r\n/g, '\n').replace(/\r/g, '\n'))
    .digest('hex')

const files = {} // key -> Set of normalized sha256
const addHash = (key, hash) => {
  if (!files[key]) files[key] = new Set()
  files[key].add(hash)
}

for (const root of SKILL_ROOTS) {
  // --- history: every blob version of every file under root, HEAD-reachable.
  // Deduplicate by git blob id before cat-file so each version hashes once.
  const seenBlobs = new Map() // blob id -> normalized sha256
  let commits = []
  try {
    commits = git('rev-list', 'HEAD', '--', root).split('\n').filter(Boolean)
  } catch {
    // fresh clone without history for this path — working tree pass still runs
  }
  for (const commit of commits) {
    let tree = ''
    try {
      tree = git('ls-tree', '-r', '-z', commit, '--', root)
    } catch { continue }
    for (const entry of tree.split('\0').filter(Boolean)) {
      // "<mode> blob <id>\t<path>"
      const tab = entry.indexOf('\t')
      if (tab < 0) continue
      const [, type, blobId] = entry.slice(0, tab).split(/\s+/)
      if (type !== 'blob') continue
      const filePath = entry.slice(tab + 1)
      const key = filePath.slice(root.length + 1)
      if (!key) continue
      if (!seenBlobs.has(blobId)) {
        seenBlobs.set(blobId, normalizedSha256(git('cat-file', 'blob', blobId)))
      }
      addHash(key, seenBlobs.get(blobId))
    }
  }
  // --- working tree: covers edited-but-uncommitted templates so the manifest
  // generated in the same change as the template edit includes the new version.
  const absRoot = path.join(REPO_ROOT, root)
  if (fs.existsSync(absRoot)) {
    const walk = (dir, rel) => {
      for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
        const r = rel ? `${rel}/${e.name}` : e.name
        if (e.isDirectory()) walk(path.join(dir, e.name), r)
        else if (e.isFile()) addHash(r, normalizedSha256(fs.readFileSync(path.join(dir, e.name))))
      }
    }
    walk(absRoot, '')
  }
}

const out = {
  schema: 1,
  comment: 'Generated by tools/gen-skill-hashes.mjs — do not edit by hand. Normalized (CRLF->LF) sha256 of every shipped version of every seeded skill file.',
  files: Object.fromEntries(
    Object.keys(files).sort().map((k) => [k, [...files[k]].sort()])
  ),
}
fs.writeFileSync(OUT_PATH, `${JSON.stringify(out, null, 1)}\n`)
const nFiles = Object.keys(out.files).length
const nHashes = Object.values(out.files).reduce((a, v) => a + v.length, 0)
console.log(`wrote ${path.relative(REPO_ROOT, OUT_PATH)}: ${nFiles} files, ${nHashes} version hashes`)
